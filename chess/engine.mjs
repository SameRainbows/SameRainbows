// Score from white's point of view.
function evaluate(chess) {
  let score = 0;
  const board = chess.board();
  for (let r = 0; r < 8; r++) {
    for (let f = 0; f < 8; f++) {
      const sq = board[r][f];
      if (!sq) continue;
      const index = sq.color === 'w' ? r * 8 + f : (7 - r) * 8 + f;
      const v = VALUE[sq.type] + PST[sq.type][index];
      score += sq.color === 'w' ? v : -v;
    }
  }
  return score;
}

function ordered(chess) {
  return chess.moves({ verbose: true }).sort((a, b) =>
    (b.captured ? VALUE[b.captured] * 10 - VALUE[b.piece] : 0) -
    (a.captured ? VALUE[a.captured] * 10 - VALUE[a.piece] : 0));
}

function search(chess, depth, alpha, beta, ply) {
  if (chess.isCheckmate()) return -100000 + ply;
  if (chess.isDraw()) return 0;
  if (depth === 0) return (chess.turn() === 'w' ? 1 : -1) * evaluate(chess);
  let best = -Infinity;
  for (const move of ordered(chess)) {
    chess.move(move);
    const score = -search(chess, depth - 1, -beta, -alpha, ply + 1);
    chess.undo();
    if (score > best) best = score;
    if (best > alpha) alpha = best;
    if (alpha >= beta) break;
  }
  return best;
}

// Picks a move for the side to play. A little noise keeps games from repeating.
export function chooseMove(chess, depth = 3, random = Math.random) {
  let best = null, bestScore = -Infinity;
  for (const move of ordered(chess)) {
    chess.move(move);
    const score = -search(chess, depth - 1, -Infinity, Infinity, 1) + random() * 12;
    chess.undo();
    if (score > bestScore) { bestScore = score; best = move; }
  }
  return best;
}
